//! Writes the typed cover and itemization Gleam modules under
//! `gleam/src/libfec/` from the `GleamType` descriptions in fec-parser
//! (feature `gleam`), formatted with `gleam format`.
//!
//! ```text
//! cargo run -p fec-gleam --bin gen               # write (make gen)
//! cargo run -p fec-gleam --bin gen -- --check    # exit 1 if stale (make check-gen)
//! cargo run -p fec-gleam --bin gen -- --out DIR  # write elsewhere
//! ```
//!
//! Module layout (Gleam forbids import cycles; a module's path is its name):
//!
//! | Rust module | Gleam module |
//! |---|---|
//! | `fec_parser::covers` (`Cover` only) | `libfec/cover` |
//! | `fec_parser::covers` (shared structs) | `libfec/cover/common` |
//! | `fec_parser::covers::form3x` | `libfec/cover/form3x` |
//! | `fec_parser::itemizations` (`Itemization` only) | `libfec/itemization` |
//! | `fec_parser::itemizations` (shared structs) | `libfec/itemization/common` |
//! | `fec_parser::itemizations::schedule_a` | `libfec/itemization/schedule_a` |
//!
//! Every file written starts with [`HEADER`]. Stale files under the output
//! directory are deleted only if they start with it, so hand-written modules
//! next to the generated ones (`libfec/internal/…`, `libfec/row.gleam`, …)
//! are never touched. `libfec/cover.gleam` and `libfec/itemization.gleam`
//! (and everything under `libfec/cover/` and `libfec/itemization/`) belong to
//! this generator.

use fec_parser::covers::Cover;
use fec_parser::gleam::{GleamDef, GleamShape, GleamTy, GleamType, GLEAM_KEYWORDS};
use fec_parser::itemizations::Itemization;
use std::collections::{BTreeMap, BTreeSet};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode, Stdio};

/// First line of every generated file; also how stale files are recognised.
const HEADER: &str = "//// Generated by crates/fec-gleam/src/bin/gen.rs. Do not edit.";

/// Rust module prefix → Gleam module path. The root enum of each family
/// lives at the Gleam path itself; the family's other `mod.rs` structs go to
/// `<path>/common`; a submodule `x` goes to `<path>/x`.
const FAMILIES: &[(&str, &str, &str)] = &[
    ("fec_parser::covers", "libfec/cover", "Cover"),
    (
        "fec_parser::itemizations",
        "libfec/itemization",
        "Itemization",
    ),
];

fn main() -> ExitCode {
    let mut check = false;
    let mut out = PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/gleam/src/libfec"));
    let mut args = std::env::args().skip(1);
    while let Some(a) = args.next() {
        match a.as_str() {
            "--check" => check = true,
            "--out" => out = PathBuf::from(args.next().expect("--out needs a directory")),
            _ => {
                eprintln!("usage: gen [--check] [--out DIR]");
                return ExitCode::from(2);
            }
        }
    }

    let files: BTreeMap<PathBuf, String> = render_all()
        .into_iter()
        .map(|(module, src)| {
            // `libfec/cover/form3x` → `<out>/cover/form3x.gleam`
            let rel = module.strip_prefix("libfec/").expect("under libfec/");
            (out.join(format!("{rel}.gleam")), gleam_format(&src))
        })
        .collect();
    let stale: Vec<PathBuf> = generated_files_in(&out)
        .into_iter()
        .filter(|p| !files.contains_key(p))
        .collect();

    if check {
        let mut problems = Vec::new();
        for (path, src) in &files {
            match std::fs::read_to_string(path) {
                Ok(on_disk) if on_disk == *src => {}
                Ok(_) => problems.push(format!("differs: {}", path.display())),
                Err(_) => problems.push(format!("missing: {}", path.display())),
            }
        }
        problems.extend(stale.iter().map(|p| format!("stale:   {}", p.display())));
        if problems.is_empty() {
            println!("{} generated Gleam modules are up to date", files.len());
            return ExitCode::SUCCESS;
        }
        for p in problems {
            eprintln!("{p}");
        }
        eprintln!("generated Gleam modules are out of date: run `make gen` in crates/fec-gleam");
        return ExitCode::FAILURE;
    }

    for (path, src) in &files {
        if std::fs::read_to_string(path).ok().as_deref() == Some(src.as_str()) {
            continue;
        }
        std::fs::create_dir_all(path.parent().unwrap()).expect("create module dir");
        std::fs::write(path, src).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
        println!("wrote   {}", path.display());
    }
    for path in stale {
        std::fs::remove_file(&path).unwrap_or_else(|e| panic!("rm {}: {e}", path.display()));
        println!("removed {}", path.display());
    }
    println!("{} generated Gleam modules", files.len());
    ExitCode::SUCCESS
}

/// Every type reachable from the two root enums, each once: `Cover`'s walk
/// then `Itemization`'s (depth-first, field order). This is also the order
/// types appear within a module, so output is stable.
fn all_defs() -> Vec<GleamDef> {
    let mut defs: Vec<GleamDef> = Vec::new();
    for d in Cover::gleam_def()
        .walk()
        .into_iter()
        .chain(Itemization::gleam_def().walk())
    {
        if !defs
            .iter()
            .any(|e| (e.rust_module, e.rust_name) == (d.rust_module, d.rust_name))
        {
            defs.push(d);
        }
    }
    defs
}

/// The Gleam module a Rust type is generated into.
fn gleam_module(rust_module: &str, rust_name: &str) -> String {
    for (prefix, path, root) in FAMILIES {
        if rust_module == *prefix {
            return if rust_name == *root {
                path.to_string()
            } else {
                format!("{path}/common")
            };
        }
        if let Some(sub) = rust_module
            .strip_prefix(prefix)
            .and_then(|s| s.strip_prefix("::"))
        {
            assert!(
                !sub.contains("::"),
                "{rust_module}::{rust_name}: nested Rust modules have no Gleam layout yet"
            );
            assert!(
                sub != "common"
                    && sub.starts_with(|c: char| c.is_ascii_lowercase())
                    && sub
                        .chars()
                        .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
                    && !GLEAM_KEYWORDS.contains(&sub),
                "{rust_module}: `{sub}` is not a usable Gleam module name"
            );
            return format!("{path}/{sub}");
        }
    }
    panic!("{rust_module}::{rust_name}: no Gleam module for this Rust module (see FAMILIES)")
}

/// Is `module` one of the root-enum modules (`libfec/cover`, `libfec/itemization`)?
fn is_root(module: &str) -> bool {
    FAMILIES.iter().any(|(_, path, _)| *path == module)
}

/// Gleam module path → source (unformatted).
fn render_all() -> BTreeMap<String, String> {
    let mut by_module: BTreeMap<String, Vec<GleamDef>> = BTreeMap::new();
    for d in all_defs() {
        by_module
            .entry(gleam_module(d.rust_module, d.rust_name))
            .or_default()
            .push(d);
    }
    by_module
        .iter()
        .map(|(module, defs)| (module.clone(), render_module(module, defs)))
        .collect()
}

/// Imports one module needs, collected while rendering its types.
#[derive(Default)]
struct Imports {
    option: bool,
    calendar: bool,
    /// Generated module → types imported unqualified (`{type Entity}`).
    unqualified: BTreeMap<String, BTreeSet<&'static str>>,
    /// Generated modules referenced qualified (`schedule_a.ScheduleA`); only
    /// the root modules do this.
    qualified: BTreeSet<String>,
}

fn last_segment(module: &str) -> &str {
    module.rsplit('/').next().unwrap()
}

impl Imports {
    fn render(&self) -> String {
        let mut lines = Vec::new();
        if self.option {
            lines.push("import gleam/option.{type Option}".to_string());
        }
        if self.calendar {
            lines.push("import gleam/time/calendar".to_string());
        }
        let modules: BTreeSet<&String> = self
            .unqualified
            .keys()
            .chain(self.qualified.iter())
            .collect();
        for m in &modules {
            let mut line = format!("import {m}");
            if let Some(types) = self.unqualified.get(*m) {
                let list: Vec<String> = types.iter().map(|t| format!("type {t}")).collect();
                line.push_str(&format!(".{{{}}}", list.join(", ")));
            }
            // Two imports ending in `common` (cover/common, itemization/common)
            // would both be called `common`. Only their types are used
            // (unqualified), so discard the module names.
            let last = last_segment(m);
            if modules.iter().filter(|o| last_segment(o) == last).count() > 1 {
                assert!(
                    !self.qualified.contains(*m),
                    "{m} is used qualified but its name collides"
                );
                line.push_str(" as _");
            }
            lines.push(line);
        }
        lines.join("\n")
    }
}

fn render_module(module: &str, defs: &[GleamDef]) -> String {
    let mut imports = Imports::default();
    let mut body = String::new();
    for d in defs {
        body.push('\n');
        body.push_str(&doc_comment(d.doc, ""));
        let name = d.rust_name;
        body.push_str(&format!("pub type {name} {{\n"));
        match &d.shape {
            GleamShape::Record { fields } => {
                body.push_str(&format!("  {name}(\n"));
                for f in fields {
                    body.push_str(&doc_comment(f.doc, "    "));
                    let ty = render_ty(&f.ty, module, &mut imports);
                    body.push_str(&format!("    {}: {ty},\n", f.name));
                }
                body.push_str("  )\n");
            }
            GleamShape::Variants { variants } => {
                for v in variants {
                    body.push_str(&doc_comment(v.doc, "  "));
                    let ty = render_ty(&v.payload, module, &mut imports);
                    body.push_str(&format!("  {}({ty})\n", v.name));
                }
            }
        }
        body.push_str("}\n");
    }

    let rust_modules: BTreeSet<&str> = defs.iter().map(|d| d.rust_module).collect();
    let rust_modules: Vec<String> = rust_modules.iter().map(|m| format!("`{m}`")).collect();
    let mut src = format!(
        "{HEADER}\n////\n//// Typed records from the Rust module {}.\n////\n\
         //// Each record's fields are in the Rust struct's order: that order is\n\
         //// the contract with the Erlang tuple the NIF builds.\n",
        rust_modules.join(", ")
    );
    let imports = imports.render();
    if !imports.is_empty() {
        src.push('\n');
        src.push_str(&imports);
        src.push('\n');
    }
    src.push_str(&body);
    src
}

fn render_ty(ty: &GleamTy, module: &str, imports: &mut Imports) -> String {
    match ty {
        GleamTy::String => "String".into(),
        GleamTy::Float => "Float".into(),
        GleamTy::Int => "Int".into(),
        GleamTy::Bool => "Bool".into(),
        GleamTy::Date => {
            imports.calendar = true;
            "calendar.Date".into()
        }
        GleamTy::Option(t) => {
            imports.option = true;
            format!("Option({})", render_ty(t, module, imports))
        }
        GleamTy::List(t) => format!("List({})", render_ty(t, module, imports)),
        GleamTy::Named(r) => {
            let target = gleam_module(r.rust_module, r.rust_name);
            if target == module {
                r.rust_name.to_string()
            } else if is_root(module) {
                // `ScheduleA(schedule_a.ScheduleA)`: the constructor and the
                // payload type share a name, so qualify the type.
                let alias = last_segment(&target).to_string();
                imports.qualified.insert(target);
                format!("{alias}.{}", r.rust_name)
            } else {
                imports
                    .unqualified
                    .entry(target)
                    .or_default()
                    .insert(r.rust_name);
                r.rust_name.to_string()
            }
        }
    }
}

/// A Rust doc comment as Gleam `///` lines at `indent`, with rustdoc's
/// intra-doc links reduced to their text.
fn doc_comment(doc: &str, indent: &str) -> String {
    let doc = clean_doc(doc);
    let doc = doc.trim_matches('\n');
    if doc.trim().is_empty() {
        return String::new();
    }
    let mut out = String::new();
    for line in doc.lines() {
        let line = line.trim_end();
        if line.is_empty() {
            out.push_str(&format!("{indent}///\n"));
        } else {
            out.push_str(&format!("{indent}/// {line}\n"));
        }
    }
    out
}

/// Rustdoc intra-doc links read badly in Gleam docs: ``[`Foo`](crate::x::Foo)``
/// and ``[`crate::x::Foo`]`` become `` `Foo` `` and `` `fec_parser::x::Foo` ``.
/// Links to URLs (`[text](https://…)`) are kept.
fn clean_doc(doc: &str) -> String {
    let mut out = String::with_capacity(doc.len());
    let mut rest = doc;
    while let Some(start) = rest.find("[`") {
        out.push_str(&rest[..start]);
        let after = &rest[start + 1..];
        // The link text: `...` up to the closing "`]".
        let Some(end) = after.find("`]") else {
            out.push_str(&rest[start..]);
            return out;
        };
        let text = &after[..end + 1];
        let mut tail = &after[end + 2..];
        if let Some(target) = tail.strip_prefix('(') {
            match target.find(')') {
                Some(close) if !target[..close].contains("://") => {
                    tail = &target[close + 1..];
                }
                _ => {
                    // A real URL link: keep it whole.
                    out.push('[');
                    out.push_str(text);
                    out.push(']');
                    rest = tail;
                    continue;
                }
            }
        }
        out.push_str(&text.replace("crate::", "fec_parser::"));
        rest = tail;
    }
    out.push_str(rest);
    out
}

/// `gleam format --stdin`, so files are written already formatted.
fn gleam_format(src: &str) -> String {
    let mut child = Command::new("gleam")
        .args(["format", "--stdin"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("run `gleam format --stdin` (is gleam on PATH?)");
    child
        .stdin
        .take()
        .unwrap()
        .write_all(src.as_bytes())
        .expect("write to gleam format");
    let out = child.wait_with_output().expect("gleam format");
    if !out.status.success() {
        panic!(
            "gleam format rejected generated source:\n{}\n--- source ---\n{src}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
    String::from_utf8(out.stdout).expect("utf-8 from gleam format")
}

/// `.gleam` files under `dir` (recursively) whose first line is [`HEADER`].
fn generated_files_in(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let Ok(entries) = std::fs::read_dir(dir) else {
        return out;
    };
    for e in entries.flatten() {
        let path = e.path();
        if path.is_dir() {
            out.extend(generated_files_in(&path));
        } else if path.extension().is_some_and(|x| x == "gleam")
            && std::fs::read_to_string(&path).is_ok_and(|s| s.lines().next() == Some(HEADER))
        {
            out.push(path);
        }
    }
    out.sort();
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn module_layout() {
        assert_eq!(gleam_module("fec_parser::covers", "Cover"), "libfec/cover");
        assert_eq!(
            gleam_module("fec_parser::covers", "Address"),
            "libfec/cover/common"
        );
        assert_eq!(
            gleam_module("fec_parser::covers::form3x", "Form3X"),
            "libfec/cover/form3x"
        );
        assert_eq!(
            gleam_module("fec_parser::itemizations", "Itemization"),
            "libfec/itemization"
        );
        assert_eq!(
            gleam_module("fec_parser::itemizations::schedule_a", "ScheduleA"),
            "libfec/itemization/schedule_a"
        );
    }

    #[test]
    fn doc_links() {
        assert_eq!(
            clean_doc("see [`crate::covers::base_form_type`]."),
            "see `fec_parser::covers::base_form_type`."
        );
        assert_eq!(
            clean_doc("a [`Cover`](crate::covers::Cover) and [`Form1M::affiliation`]"),
            "a `Cover` and `Form1M::affiliation`"
        );
        let url = "([fecfrm13.pdf p1](https://www.fec.gov/x.pdf#page=1)) and [`X`](https://e.com)";
        assert_eq!(clean_doc(url), url);
        assert_eq!(clean_doc("[`unterminated"), "[`unterminated");
    }
}
